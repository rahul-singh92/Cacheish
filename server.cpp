static void die(const char *msg)
{
    int err = errno;
    fprintf(stderr, "[%d] %s: %s\n", err, msg, strerror(err));
    abort();
}

static void msg(const char *msg)
{
    fprintf(stderr, "%s\n", msg);
}

static void msg_errno(const char *msg)
{
    fprintf(stderr, "[error: %d] %s\n", errno, msg);
}

static void fd_set_nb(int fd)
{
    errno = 0;
    int flags = fcntl(fd, F_GETFL, 0);
    if (errno)
    {
        die("fcntl errno");
        return;
    }

    flags |= O_NONBLOCK;

    errno = 0;
    (void)fcntl(fd, F_SETFL, flags);
    if (errno)
    {
        die("fcntl error");
    }
}

const size_t k_max_msg = 32 << 20;

struct Conn
{
    int fd = -1;
    // for event loop
    bool want_read = false;
    bool want_write = false;
    bool want_close = false;
    // buffer input and output
    std::vector<uint8_t> incoming; // data to be parsed by the application
    std::vector<uint8_t> outgoing; // responses generated by the application
};

static void buf_append(std::vector<uint8_t> &buf, const uint8_t *data, size_t len)
{
    buf.insert(buf.end(), data, data + len);
}

static void buf_consume(std::vector<uint8_t> &buf, size_t n)
{
    buf.erase(buf.begin(), buf.begin() + n);
}

// application callback when listening socket is ready
static Conn *handle_accept(int fd)
{
    // accept
    struct sockaddr_in client_addr = {};
    socklen_t addrlen = sizeof(client_addr);
    int connfd = accept(fd, (struct sockaddr *)&client_addr, &addrlen);
    if (connfd < 0)
    {
        msg_errno("accept() error");
        return NULL;
    }

    uint32_t ip = client_addr.sin_addr.s_addr;
    fprintf(stderr, "new client from %u.%u.%u.%u:%u\n", 
        ip & 255, (ip >> 8) & 255, (ip >> 16) & 255, ip >> 24,
        ntohs(client_addr.sin_port)
    );

    // set the new connection to non blocking mode
    fd_set_nb(connfd);

    Conn *conn = new Conn();
    conn -> fd = connfd;
    conn -> want_read = true;
    return conn;
}

// request if enough data
static bool try_one_request(Conn *conn)
{
    if (conn -> incoming.size() < 4)
    {
        return false; // want read
    }
    uint32_t len = 0;
    memcpy(&len, conn -> incoming.data(), 4);
    if (len > k_max_msg)
    {
        msg("too long");
        conn -> want_close = true;
        return false; // want close
    }

    // message body
    if (4 + len > conn -> incoming.size())
    {
        return false; // want read
    }
    const uint8_t *request = &conn -> incoming[4];

    // got one request, do some application logic
    printf("client says: len:%d data:%.*s\n", 
        len, len < 100 ? len : 100, request
    );

    // generate the response
    buf_append(conn -> outgoing, (const uint8_t *)&len, 4);
    buf_append(conn -> outgoing, request, len);

    // application logic done, remove the request message
    buf_consume(conn -> incoming, 4 + len);
    return true;
}

static void handle_write(Conn *conn)
{
    assert(conn -> outgoing.size() > 0);
    ssize_t rv = write(conn -> fd, &conn -> outgoing[0], conn -> outgoing.size());
    if (rv < 0 && errno == EAGAIN)
    {
        return; //actually not ready
    }
    if (rv < 0)
    {
        msg_errno("write() error");
        conn -> want_close = true;
        return;
    }

    // remove written data from outgoing
    buf_consume(conn -> outgoing, (size_t)rv);

    if (conn -> outgoing.size() == 0)
    {
        conn -> want_read = true;
        conn -> want_write = false;
    } // else want write
}

static void handle_read(Conn *conn)
{
    uint8_t buf[64 * 1024];
    ssize_t rv = read(conn -> fd, buf, sizeof(buf));
    if (rv < 0 && errno == EAGAIN)
    {
        return;
    }

    if (rv < 0)
    {
        msg_errno("read() error");
        conn -> want_close = true;
        return;
    }

    if (rv == 0)
    {
        if (conn -> incoming.size() == 0)
        {
            msg("client closed");
        }
        else
        {
            msg("unexpected EOF");
        }
        conn -> want_close = true;
        return;
    }
    // got some new data
    buf_append(conn -> incoming, buf, (size_t)rv);

    // parse request and generate response
    while (try_one_request(conn)) {}

    if(conn -> outgoing.size() > 0)
    {
        conn -> want_read = false;
        conn -> want_write = true;
        return handle_write(conn);
    }
}

int main()
{
    // listening socket using IPv4 with TCP
    int fd = socket(AF_INET, SOCK_STREAM, 0);
    if (fd < 0)
    {
        die("socket()");
    }
    int val = 1;
    setsockopt(fd, SOL_SOCKET, SO_REUSEADDR, &val, sizeof(val));
    
    struct sockaddr_in addr = {};
    addr.sin_family = AF_INET;
    addr.sin_port = ntohs(1234);
    addr.sin_addr.s_addr = ntohl(0); // 0.0.0.0
    int rv = bind(fd, (const struct sockaddr *)&addr, sizeof(addr));
    if (rv)
    {
        die("bind()");
    }

    // set listen fd to non blocking mode
    fd_set_nb(fd);

    rv = listen(fd, SOMAXCONN);
    if (rv)
    {
        die("listen()");
    }

    // a map all client connections, keyed by fd
    std::vector<Conn *> fd2Conn;
    // even loop
    std::vector<struct pollfd> poll_args;
    while (true)
    {
        poll_args.clear();
        // listening socket in first position
        struct pollfd pfd = {fd, POLLIN, 0};
        poll_args.push_back(pfd);

        for (Conn *conn: fd2Conn)
        {
            if (!conn)
            {
                continue;
            }

            // always poll() for error
            struct pollfd pfd = {conn -> fd, POLLERR, 0};
            if (conn -> want_read)
            {
                pfd.events |= POLLIN;
            }
            if (conn -> want_write)
            {
                pfd.events |= POLLOUT;
            }
            poll_args.push_back(pfd);
        }

        int rv = poll(poll_args.data(), (nfds_t)poll_args.size(), -1);
        if (rv < 0 && errno == EINTR)
        {
            continue; // not an Error
        }
        if (rv < 0)
        {
            die("poll");
        }

        // handle the listening socket
        if (poll_args[0].revents)
        {
            if (Conn *conn = handle_accept(fd))
            {
                if (fd2Conn.size() <= (size_t)conn -> fd)
                {
                    fd2Conn.resize(conn -> fd + 1);
                }
                assert(!fd2Conn[conn -> fd]);
                fd2Conn[conn -> fd] = conn;
            }
        }

        // handle connection sockets
        for (size_t i = 1; i < poll_args.size(); ++i)
        {
            uint32_t ready = poll_args[i].revents;
            if (ready == 0)
            {
                continue;
            }

            Conn *conn = fd2Conn[poll_args[i].fd];
            if (ready & POLLIN)
            {
                assert(conn -> want_read);
                handle_read(conn);
            }
            if (ready & POLLOUT)
            {
                assert(conn -> want_write);
                handle_write(conn);
            }

            if ((ready & POLLERR) || conn -> want_close)
            {
                (void)close(conn -> fd);
                fd2Conn[conn -> fd] = NULL;
                delete conn;
            }
        }
    }
    return 0;
}   